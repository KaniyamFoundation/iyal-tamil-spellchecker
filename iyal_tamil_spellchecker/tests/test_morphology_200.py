def test_complex_derived_words_validation(client):
    """
    Rigorously iterates through hundreds of stacked phonological inflection configurations.
    """
    for word in COMPLEX_TAMIL_WORDS:
        res = client.post("/v1/spellcheck", json={"text": word})
        data = json.loads(res.data)
        assert res.status_code == 200
        word_data = data["results"][0]
        assert word_data["correct"] is True, f"Linguistic failure validating derived form: {word}"
